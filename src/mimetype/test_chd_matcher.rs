use super::*;

#[test]
fn test_valid() {
    assert!(chd_matcher(&[0x4D, 0x43, 0x6F, 0x6D, 0x70, 0x72, 0x48, 0x44]));
}

#[test]
fn test_invalid() {
    assert!(!chd_matcher(&[0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00]));
}

#[test]
fn test_too_short() {
    assert!(!chd_matcher(&[0x4D, 0x43, 0x6F, 0x6D, 0x70, 0x72, 0x48]));
}
