/*
 * smelt: read an ORE as the disc or ROM it holds.
 *
 * An smelt_ingot belongs to one thread at a time: it caches what it decodes,
 * so every call on it may change it. smelt_clone gives another thread an
 * ingot of its own over the same file and store.
 *
 * Functions return SMELT_OK or an error code; smelt_last_error gives the
 * calling thread's last error as text. A buffer an output is written to is
 * given with its capacity in *len, which comes back as the length needed:
 * SMELT_ERR_BUFFER_TOO_SMALL when it is more, buf NULL to ask for it.
 */

